const LEGACY_SPANISH = Object.fromEntries(
  Object.entries(LEGACY_ENGLISH).map(([spanish, english]) => [english, spanish]),
);

function translateDynamic(value: string, locale: Locale): string | null {
  if (locale !== "en-US") return null;
  const rules: Array<[RegExp, (...values: string[]) => string]> = [
    [/^(\d+) de (\d+) títulos publicados$/, (a, b) => `${a} of ${b} released titles`],
    [/^(\d+) personales$/, (a) => `${a} personal items`],
    [/^(\d+) desbloqueados$/, (a) => `${a} unlocked`],
    [/^(\d+) solicitudes$/, (a) => `${a} requests`],
    [/^(\d+) solicitud$/, (a) => `${a} request`],
    [/^(\d+) elementos$/, (a) => `${a} items`],
    [/^(\d+) capítulos vistos$/, (a) => `${a} episodes watched`],
    [/^Última sincronización: (.+)$/, (date) => `Last sync: ${date}`],
    [/^Amigos desde (.+)$/, (date) => `Friends since ${date}`],
    [/^(\d+) de (\d+) títulos$/, (a, b) => `${a} of ${b} titles`],
    [/^(.+) · T(\d+)$/, (title, season) => `${LEGACY_ENGLISH[title] || title} · S${season}`],
    [
      /^(.+) forma parte del catálogo audiovisual de Marvel\. Abre sus conexiones para descubrir dónde encaja sin revelar acontecimientos posteriores\.$/,
      (title) =>
        `${LEGACY_ENGLISH[title] || title} is part of Marvel's audiovisual catalog. Open its connections to see where it fits without revealing later events.`,
    ],
  ];
  for (const [pattern, render] of rules) {
    const match = value.match(pattern);
    if (match) return render(...match.slice(1));
  }
  return null;
}

function translateDynamicToSpanish(value: string): string | null {
  const rules: Array<[RegExp, (...values: string[]) => string]> = [
    [/^(\d+) of (\d+) released titles$/, (a, b) => `${a} de ${b} títulos publicados`],
    [/^(\d+) personal items$/, (a) => `${a} personales`],
    [/^(\d+) unlocked$/, (a) => `${a} desbloqueados`],
    [/^(\d+) requests$/, (a) => `${a} solicitudes`],
    [/^(\d+) request$/, (a) => `${a} solicitud`],
    [/^(\d+) items$/, (a) => `${a} elementos`],
    [/^(\d+) episodes watched$/, (a) => `${a} capítulos vistos`],
    [/^Last sync: (.+)$/, (date) => `Última sincronización: ${date}`],
    [/^Friends since (.+)$/, (date) => `Amigos desde ${date}`],
    [/^(\d+) of (\d+) titles$/, (a, b) => `${a} de ${b} títulos`],
    [/^(.+) · S(\d+)$/, (title, season) => `${LEGACY_SPANISH[title] || title} · T${season}`],
    [
      /^(.+) is part of Marvel's audiovisual catalog\. Open its connections to see where it fits without revealing later events\.$/,
      (title) =>
        `${LEGACY_SPANISH[title] || title} forma parte del catálogo audiovisual de Marvel. Abre sus conexiones para descubrir dónde encaja sin revelar acontecimientos posteriores.`,
    ],
  ];
  for (const [pattern, render] of rules) {
    const match = value.match(pattern);
    if (match) return render(...match.slice(1));
  }
  return null;
}

export function translateLegacy(value: string, locale: Locale) {
  const trimmed = value.trim();
  if (!trimmed) return value;
  const replacement =
    locale === "en-US"
      ? LEGACY_ENGLISH[trimmed] || translateDynamic(trimmed, locale)
      : LEGACY_SPANISH[trimmed] || translateDynamicToSpanish(trimmed);
  if (!replacement) return value;
  return value.replace(trimmed, replacement);
}
